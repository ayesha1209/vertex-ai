"""
Build static COA/TDS/MSDS templates from docs/*.docx.
Run when reference DOCX files change:  python scripts/build_reference_templates.py
Writes app/prompts/reference_templates_generated.py (used at runtime; no DOCX needed).
"""

import re
from pathlib import Path


def _docx_to_text(path: Path) -> str:
    from docx import Document
    doc = Document(path)
    lines = []
    for p in doc.paragraphs:
        lines.append(p.text)
    for t in doc.tables:
        for row in t.rows:
            lines.append("|".join(cell.text.strip().replace("\n", " ") for cell in row.cells))
        lines.append("---TABLE---")
    return "\n".join(lines)


def _coa_placeholders(text: str) -> str:
    replacements = [
        ("Sodium Sulphate (Anhydrous)", "[Product Name – as per enquiry]"),
        ("Sodium Sulphate Anhydrous", "[Product Name]"),
        ("Na₂SO₄", "[Chemical Formula]"),
        ("7757-82-6", "[CAS No.]"),
        ("28331100", "[HSN Code]"),
        ("SS-2602-24", "[Batch No.]"),
        ("Feb 2026", "[Mfg. Date]"),
        ("Feb 2028", "[Expiry Date]"),
        ("Detergent / Industrial Grade", "[Grade]"),
        ("25 Kg HDPE Laminated Bags", "[Packing]"),
        ("vertex chemical corporation", "[Company Name / For:]"),
        ("99.42 %", "[Result %]"),
        ("0.21 %", "[Result %]"),
        ("0.018 %", "[Result %]"),
        ("7.21", "[Result]"),
        ("0.14 %", "[Result %]"),
        ("0.0008 %", "[Result %]"),
        ("0.032 %", "[Result %]"),
        ("0.018 %", "[Result %]"),
        ("< 0.001 %", "[Result %]"),
        ("69.82 %", "[Result %]"),
        ("1.48 g/cm³", "[Result]"),
        ("0.19 %", "[Result %]"),
        (
            "The above material complies with the Industrial/Detergent Grade Sodium Sulphate specification.",
            "The above material complies with the [Grade] [Product Name] specification.",
        ),
    ]
    out = text
    for old, new in replacements:
        out = out.replace(old, new)
    return out


def _tds_placeholders(text: str) -> str:
    out = text.replace("Sodium Sulphate (Na₂SO₄)", "[Product Name (Chemical Formula)]")
    out = out.replace("Sodium Sulphate", "[Product Name]")
    out = out.replace("142.04 g/mol", "[Molecular Weight]")
    out = out.replace("7757-82-6", "[CAS No.]")
    out = out.replace("7727-73-3", "[CAS No.]")
    # Remove decahydrate/Glauber's salt so model does not hallucinate it for other products
    for phrase in [
        "(Decahydrate – Glauber's Salt)",
        "(Decahydrate - Glauber's Salt)",
        "Decahydrate – Glauber's Salt",
        "(Decahydrate – Glauber\u2019s Salt)",
        "(Glauber's salt)",
        "Glauber's salt",
        "(Glauber\u2019s salt)",
    ]:
        out = out.replace(phrase, "")
    # Remove any whole line that still contains both Decahydrate and Glauber
    out = re.sub(r"\n[^\n]*Decahydrate[^\n]*Glauber[^\n]*\n", "\n", out)
    out = re.sub(r"\n[^\n]*Glauber[^\n]*Decahydrate[^\n]*\n", "\n", out)
    out = out.replace("CAS No.: [CAS No.]\nCAS No.: [CAS No.]", "CAS No.: [CAS No.]")
    out = out.replace("CAS No.: [CAS No.] (Anhydrous)", "CAS No.: [CAS No.]")
    out = out.replace("28331100", "[HSN Code]")
    out = out.replace("231-820-9", "[EINECS No.]")
    out = out.replace("India / China (as per supply)", "[Origin]")
    return out


def _msds_placeholders(text: str) -> str:
    out = text.replace("Sodium Sulphate (Anhydrous)", "[Product Name]")
    out = out.replace("Sodium Sulphate", "[Product Name]")
    out = out.replace("Na₂SO₄", "[Chemical Formula]")
    out = out.replace("7757-82-6", "[CAS No.]")
    out = out.replace("28331100", "[HSN Code]")
    out = out.replace("142.04 g/mol", "[Molecular Weight]")
    out = out.replace("Aksh Chemicals", "[Supplier]")
    out = out.replace("+91-XXXXXXXXXX", "[Emergency Contact]")
    out = out.replace("≥ 99%", "[Concentration %]")
    return out


def _escape_for_python_string(s: str) -> str:
    """Escape so we can put inside triple-quoted string."""
    return s.replace("\\", "\\\\").replace('"""', '\\"""')


def main() -> None:
    backend = Path(__file__).resolve().parent.parent
    docs_dir = backend.parent / "docs"
    out_path = backend / "app" / "prompts" / "reference_templates_generated.py"

    coa_path = docs_dir / "certificate of analysis (COA) Sodium Sulphate.docx"
    tds_path = docs_dir / "format tds (Technical datasheet).docx"
    msds_path = docs_dir / "Material Safety Data Sheet (MSDS).docx"

    coa = _coa_placeholders(_docx_to_text(coa_path)) if coa_path.exists() else ""
    tds = _tds_placeholders(_docx_to_text(tds_path)) if tds_path.exists() else ""
    msds = _msds_placeholders(_docx_to_text(msds_path)) if msds_path.exists() else ""

    content = f'''# Auto-generated by scripts/build_reference_templates.py – do not edit by hand.
# Regenerate when docs/*.docx change.

COA_TEMPLATE = """
{_escape_for_python_string(coa)}
"""

TDS_TEMPLATE = """
{_escape_for_python_string(tds)}
"""

MSDS_TEMPLATE = """
{_escape_for_python_string(msds)}
"""
'''
    out_path.write_text(content, encoding="utf-8")
    print("Wrote", out_path)


if __name__ == "__main__":
    main()
